test('basic views preload in parallel and a cold source view preserves navigation', async () => {
  let release, requested, recordRequested
  const recordStarted = new Promise(resolve => { recordRequested = resolve })
  await page.route('**/src/components/RecordView.tsx*', async route => {
    recordRequested()
    await route.continue()
  })
  const gate = new Promise(resolve => { release = resolve })
  const requestStarted = new Promise(resolve => { requested = resolve })
  await page.route('**/src/components/SourceEditorView.tsx*', async route => {
    requested()
    await gate
    await route.continue()
  })
  try {
    await page.goto(server.resolvedUrls.local[0])
    // 源码模块被阻塞时，记录模块仍自动发起加载，表格也能正常显示。
    await Promise.all([requestStarted, recordStarted])
    await page.locator('.data-table').waitFor()
    await page.locator('.view-picker').getByRole('tab', { name: '源码', exact: true }).click()
    await page.locator('.content-area').getByRole('status').waitFor()
    assert.equal(await page.locator('.layout-navigation').isVisible(), true)
    assert.equal(await page.locator('.document-tabs').isVisible(), true)
    await page.locator('.file-tree [data-file-path="data/npc.cfd"]').first().click()
    await page.locator('.data-table').waitFor()
    assert.equal(await page.locator('.layout-navigation').isVisible(), true)
    assert.deepEqual(errors, [])
  } finally { release(); await page.unrouteAll({ behavior: 'wait' }) }
})

