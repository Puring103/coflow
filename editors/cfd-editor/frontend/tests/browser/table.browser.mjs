test('second click places a collapsed caret at the clicked character', async () => {
  const field = input(0)
  await field.click()
  const point = await field.locator('..').locator('.cell-string-preview').evaluate(el => {
    const range = document.createRange()
    range.setStart(el.firstChild, 1); range.setEnd(el.firstChild, 2)
    const rect = range.getBoundingClientRect()
    return { x: rect.left + 1, y: rect.top + rect.height / 2 }
  })
  await page.mouse.move(point.x, point.y)
  await page.mouse.down({ clickCount: 2 })
  await page.mouse.up({ clickCount: 2 })
  const selection = await field.evaluate(el => [el.selectionStart, el.selectionEnd])
  assert.equal(selection[0], selection[1])
  assert.equal(selection[0], 1)
})


