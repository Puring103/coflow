import assert from 'node:assert/strict'
import { before, after, beforeEach, test } from 'node:test'
import { fileURLToPath } from 'node:url'
import { createServer } from 'vite'
import { chromium } from 'playwright'

let server, browser, page
const errors = []
before(async () => {
  server = await createServer({ root: fileURLToPath(new URL('../..', import.meta.url)), server: { port: 0, strictPort: false, host: '127.0.0.1' } })
  await server.listen()
  browser = await chromium.launch({ headless: true, executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH || undefined })
  page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
  page.setDefaultTimeout(5000)
  page.setDefaultNavigationTimeout(20000)
  page.on('pageerror', error => errors.push(error.message))
})
after(async () => { await browser?.close(); await server?.close() })
beforeEach(async () => {
  errors.length = 0
  await page.goto(`${server.resolvedUrls.local[0]}previews/cells.html`)
  await page.evaluate(() => localStorage.removeItem('coflow-cell-preview-row-heights'))
  await page.reload()
  await page.locator('td[data-field="value"] textarea').first().waitFor()
})
const record = name => page.locator(`tr[data-coordinate-id="Preview::${encodeURIComponent(name)}"]`)
const field = (root, label) => root.locator('.dc-row-field').filter({ has: page.locator('.dc-row-label-text', { hasText: new RegExp(`^${label}$`) }) }).first()
const close = async () => { await page.getByRole('button', { name: '关闭编辑弹窗' }).click(); await page.waitForTimeout(180) }
const expand = async name => {
  const cell = record(name).locator('td[data-field="value"]')
  await cell.hover()
  await cell.getByRole('button', { name: '放大编辑单元格' }).click()
  await page.getByRole('dialog').waitFor()
  await page.waitForTimeout(220)
  return page.getByRole('dialog')
}

test('simple values edit inline; complex blanks and IDs open the appropriate dialog', async () => {
  const cell = record('简单值，直接编辑').locator('td[data-field="value"]')
  const water = field(cell, '初始水量')
  await water.locator('textarea').fill('72')
  await water.locator('textarea').press('Enter')
  await water.locator('textarea').dblclick()
  assert.equal(await page.getByRole('dialog').count(), 0)
  assert.equal(await water.locator('textarea').inputValue(), '72')
  await page.locator('.table-scroll').focus()
  await cell.dblclick({ position: { x: 3, y: 3 } })
  assert.equal(await page.getByRole('dialog').count(), 1)
  assert.equal(await page.getByRole('dialog').getAttribute('aria-label'), '单元格详情面板')
  assert.equal(await page.getByRole('dialog').locator('.inspector-title').count(), 0)
  await close()
  await record('简单值，直接编辑').locator('td.sticky-key-column').dblclick()
  assert.equal(await page.getByRole('dialog').getAttribute('aria-label'), '记录详情面板')
  await close()
  assert.deepEqual(errors, [])
})

test('dialog reuses enum, reference and read-only controls and saves before closing', async () => {
  const dialog = await expand('简单值，直接编辑')
  await field(dialog, '品质').locator('input').click()
  await page.getByRole('option', { name: 'Common', exact: true }).click()
  assert.equal(await field(dialog, '品质').locator('input').inputValue(), 'Common')
  await field(dialog, '引用模板').getByRole('button', { name: '打开引用记录' }).click()
  assert.equal(await page.locator('.reference-panel').count(), 1)
  await page.getByRole('button', { name: '关闭', exact: true }).click()
  await field(dialog, '初始水量').locator('textarea').fill('bad-number')
  await close()
  assert.equal(await page.getByRole('dialog').count(), 1)
  assert.equal(await field(dialog, '初始水量').locator('[role="alert"]').count(), 1)
  await field(dialog, '初始水量').locator('textarea').fill('95')
  await close()
  assert.equal(await page.getByRole('dialog').count(), 0)
  const readOnly = await expand('可编辑与只读并存')
  assert.equal(await field(readOnly, 'BaseValue').locator('textarea').count(), 0)
  await close()
  assert.deepEqual(errors, [])
})

