test('row resizing reveals content, persists independently and supports reset', async () => {
  const row = record('简单值，直接编辑')
  const before = await row.boundingBox()
  assert.equal(await row.locator('.cell-complex-overflow').count(), 1)
  const handle = row.getByRole('separator', { name: '调整行高' }).first()
  const bounds = await handle.boundingBox()
  await page.mouse.move(bounds.x + 20, bounds.y + 2)
  await page.mouse.down()
  await page.mouse.move(bounds.x + 20, bounds.y + 132, { steps: 6 })
  await page.mouse.up()
  assert.ok((await row.boundingBox()).height > before.height + 90)
  assert.equal(await row.locator('.cell-complex-overflow').count(), 0)
  const saved = JSON.parse(await page.evaluate(() => localStorage.getItem('coflow-cell-preview-row-heights')))
  assert.ok(saved[`Preview::${encodeURIComponent('简单值，直接编辑')}`] > 200)
  await page.locator('th').first().click()
  assert.ok((await row.boundingBox()).height > 200)
  await page.reload()
  assert.ok((await row.boundingBox()).height > 200)
  await page.getByRole('button', { name: '恢复默认行高' }).click()
  assert.ok((await row.boundingBox()).height < 200)
  assert.deepEqual(errors, [])
})


test('selection reveals complex content without editing and backdrop close retains its final frame', async () => {
  const cell = record('简单值，直接编辑').locator('td[data-field="value"]')
  const rowHeight = await cell.locator('..').evaluate(element => element.getBoundingClientRect().height)
  await cell.click({ position: { x: 3, y: 3 } })
  const viewport = cell.locator('.cell-complex-viewport')
  assert.equal(await viewport.evaluate(element => getComputedStyle(element).maskImage), 'none')
  assert.equal(await viewport.evaluate(element => getComputedStyle(element).overflowY), 'visible')
  assert.equal(await cell.locator('..').evaluate(element => element.getBoundingClientRect().height), rowHeight)
  assert.equal(await page.getByRole('dialog').count(), 0)
  assert.equal(await cell.evaluate(element => getComputedStyle(element, '::after').display), 'none')
  const surface = await cell.locator('.cell-complex-content').boundingBox()
  const bounds = await cell.boundingBox()
  assert.ok(Math.abs(surface.x - bounds.x) <= 2)
  assert.ok(Math.abs(surface.width - bounds.width) <= 2)
  const originalBounds = await cell.boundingBox()
  await page.mouse.move(originalBounds.x + originalBounds.width / 2, originalBounds.y + originalBounds.height - 1)
  assert.equal(await page.evaluate(({ x, y }) => !!document.elementFromPoint(x, y)?.closest('.table-row-resizer'), { x: originalBounds.x + originalBounds.width / 2, y: originalBounds.y + originalBounds.height - 1 }), false)
  assert.equal(await cell.locator('.cell-complex-content').evaluate(element => getComputedStyle(element).animationName), 'none')
  const button = cell.getByRole('button', { name: '放大编辑单元格' })
  assert.equal(await button.evaluate(element => getComputedStyle(element).left), '1px')
  assert.equal(await button.evaluate(element => element.getBoundingClientRect().width), 18)
  await button.click()
  await page.waitForTimeout(220)
  await page.locator('.inspector-modal-backdrop').click({ position: { x: 5, y: 5 } })
  // 关闭末帧必须持有，动画结束至卸载之间不能恢复可见的大窗口。
  const fills = await page.getByRole('dialog').evaluate(element => element.getAnimations().map(animation => animation.effect.getTiming().fill))
  assert.ok(fills.includes('forwards'))
  await page.getByRole('dialog').waitFor({ state: 'detached' })
  await button.click()
  await page.waitForTimeout(220)
  await page.getByRole('dialog').locator('.inspector-head').click({ position: { x: 5, y: 5 } })
  assert.equal(await page.getByRole('dialog').count(), 1)
  await close()
  assert.deepEqual(errors, [])
})


