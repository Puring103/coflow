test('folding preserves row density and reference presentation across surfaces and themes', async () => {
  const cell = record('对象数组').locator('td[data-field="value"]')
  const inlineHeader = cell.locator('.dc-row-structure[data-list-item="true"]').first()
  const collapsedHeight = (await inlineHeader.boundingBox()).height
  await inlineHeader.click()
  assert.equal(await inlineHeader.locator('.dc-business-summary').count(), 0)
  assert.equal((await inlineHeader.boundingBox()).height, collapsedHeight)
  assert.equal((await field(cell, 'Item').boundingBox()).height, collapsedHeight)
  await inlineHeader.click()
  assert.equal(await inlineHeader.locator('.dc-business-summary').count(), 1)
  assert.equal((await inlineHeader.boundingBox()).height, collapsedHeight)
  const dialog = await expand('对象数组')
  assert.equal(await dialog.locator('.inspector-title').count(), 0)
  assert.equal(await dialog.locator('.dc-row[data-field-name="value"]').count(), 0)
  const header = dialog.locator('.dc-row-structure[data-list-item="true"]').first()
  const before = (await header.boundingBox()).height
  await header.click()
  const count = dialog.locator('.dc-row-structure').filter({ has: page.locator('.dc-row-label-text', { hasText: /^Count$/ }) })
  await count.click()
  assert.equal(await count.locator('.dc-business-summary').count(), 0)
  assert.equal((await header.boundingBox()).height, before)
  const heights = await dialog.locator('.dc-row').evaluateAll(rows => rows.map(row => row.getBoundingClientRect().height))
  assert.ok(heights.every(height => height === before))
  for (const theme of ['dark', 'light']) {
    await page.evaluate(value => { document.documentElement.dataset.theme = value }, theme)
    await page.mouse.move(1400, 950)
    const styles = await dialog.locator('.vc-ref, .dc-pill-wrap-ref').evaluateAll(pills => pills.map(pill => {
      const style = getComputedStyle(pill)
      const button = pill.querySelector('.reference-open')
      const text = pill.querySelector('.vc-ref-key, input')
      return { color: style.backgroundColor, border: style.borderColor,
        height: pill.getBoundingClientRect().height,
        icon: button.querySelector('path').getAttribute('d'),
        gap: text.getBoundingClientRect().left - button.getBoundingClientRect().right,
        padding: getComputedStyle(text).paddingLeft }
    }))
    assert.ok(styles.length >= 2)
    assert.ok(styles.every(style => JSON.stringify(style) === JSON.stringify(styles[0])))
  }
  // 摘要中的引用仍能打开记录，不会把点击误当作折叠操作。
  const collapsedHeader = dialog.locator('.dc-row-structure[data-list-item="true"]').nth(1)
  await collapsedHeader.getByRole('button', { name: '打开引用记录' }).click()
  assert.equal(await page.locator('.reference-panel').count(), 1)
  assert.equal(await collapsedHeader.getAttribute('aria-expanded'), 'false')
  await page.getByRole('button', { name: '关闭', exact: true }).click()
  await close()
  assert.deepEqual(errors, [])
})


test('polymorphic types stay before the summary in the value area without losing editing', async () => {
  const dialog = await expand('多态字段')
  const effect = dialog.locator('.dc-row-structure').filter({ has: page.locator('.dc-row-label-text', { hasText: /^Effect$/ }) })
  assert.equal(await effect.locator('.dc-row-value input[aria-label="选择具体类型"]').inputValue(), 'Damage')
  assert.equal(await effect.locator('.dc-business-summary').count(), 1)
  assert.equal(await effect.locator('.dc-row-label input').count(), 0)
  const typeBounds = await effect.locator('.dc-structure-type-control').boundingBox()
  const summaryBounds = await effect.locator('.dc-business-summary').boundingBox()
  assert.ok(typeBounds.x + typeBounds.width <= summaryBounds.x)

  await effect.locator('.dc-row-label-text').click()
  assert.equal(await effect.locator('.dc-row-label input').count(), 0)
  assert.equal(await effect.locator('.dc-row-value input[aria-label="选择具体类型"]').inputValue(), 'Damage')
  assert.equal(await effect.locator('.dc-business-summary').count(), 0)
  await effect.getByRole('combobox', { name: '选择具体类型' }).click()
  await page.getByRole('option', { name: 'Heal', exact: true }).click()
  assert.equal(await effect.getAttribute('aria-expanded'), 'true')
  assert.equal(await effect.getByRole('combobox', { name: '选择具体类型' }).inputValue(), 'Heal')
  assert.equal(await field(dialog, 'Range').count(), 0)
  assert.equal(await field(dialog, 'Amount').locator('textarea').inputValue(), '8')
  await effect.locator('.dc-row-label-text').click()
  assert.equal(await effect.locator('.dc-row-value input').inputValue(), 'Heal')
  const passive = dialog.locator('.dc-row-structure').filter({ has: page.locator('.dc-row-label-text', { hasText: /^Passive$/ }) })
  assert.equal(await passive.locator('.dc-row-value .dc-structure-type').innerText(), 'Heal')
  assert.equal(await passive.getByRole('combobox').count(), 0)
  await passive.locator('.dc-row-label-text').click()
  assert.equal(await passive.locator('.dc-row-value .dc-structure-type').innerText(), 'Heal')
  await close()
  assert.deepEqual(errors, [])
})
