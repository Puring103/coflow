//! 从语言实际使用的 Unicode 表生成 Loader 的标识符表。
use std::fmt::Write;

fn main() -> Result<(), Box<dyn std::error::Error>> {
    let mut output = String::from("// Generated by: cargo run -p coflow-language --example export_csharp_xid\nnamespace Coflow.Loader\n{\ninternal static class CfdXid\n{\n");
    writeln!(
        output,
        "    // Unicode {:?}; 与 Rust 词法器使用同一份 XID 数据。",
        unicode_ident::UNICODE_VERSION
    )?;
    for (name, predicate) in [
        ("Start", unicode_ident::is_xid_start as fn(char) -> bool),
        (
            "Continue",
            unicode_ident::is_xid_continue as fn(char) -> bool,
        ),
    ] {
        writeln!(
            output,
            "    private static readonly int[] {name}Ranges = {{"
        )?;
        let mut start = None;
        for code in 0..=0x0011_0000 {
            let valid = char::from_u32(code).is_some_and(predicate);
            if valid && start.is_none() {
                start = Some(code);
            }
            if !valid {
                if let Some(first) = start.take() {
                    writeln!(output, "        0x{first:X}, 0x{:X},", code - 1)?;
                }
            }
        }
        output.push_str("    };\n");
    }
    output.push_str("    internal static bool Contains(int value, bool start)\n    {\n        var ranges = start ? StartRanges : ContinueRanges;\n        var low = 0;\n        var high = ranges.Length / 2 - 1;\n        while (low <= high)\n        {\n            var middle = low + (high - low) / 2;\n            if (value < ranges[middle * 2]) high = middle - 1;\n            else if (value > ranges[middle * 2 + 1]) low = middle + 1;\n            else return true;\n        }\n        return false;\n    }\n}\n}\n");
    let path = std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../../runtimes/csharp/Coflow.Loader/Cfd/CfdXid.Generated.cs");
    std::fs::write(path, output)?;
    Ok(())
}
