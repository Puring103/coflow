use crate::{
    names::{csharp_ident_error, csharp_identifier, metadata_identifier},
    CsharpCodegenError, GeneratedFile,
};
use coflow_codegen::IdAsEnumValues;
use coflow_language::cft::{
    CftConstValue, CftEnum, CftField, CftSchema, CftSchemaDefaultValue, CftType, CftValueType,
};
use std::fmt::Write as _;
use std::{collections::BTreeSet, path::PathBuf};

type Result<T> = std::result::Result<T, CsharpCodegenError>;

fn quote(text: &str) -> String {
    let mut out = String::from("\"");
    for ch in text.chars() {
        match ch {
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            // Unicode 行/段分隔符不是 Rust 控制字符，但会截断 C# 普通字符串。
            '\u{2028}' => out.push_str("\\u2028"),
            '\u{2029}' => out.push_str("\\u2029"),
            ch if ch.is_control() => {
                let _ = write!(out, "\\u{:04X}", u32::from(ch));
            }
            ch => out.push(ch),
        }
    }
    out.push('"');
    out
}

fn validate_ident(name: &str) -> Result<()> {
    if let Some(error) = csharp_ident_error(name) {
        return Err(CsharpCodegenError::new(format!(
            "invalid C# identifier `{name}`: {error}"
        )));
    }
    Ok(())
}

// 业务类型引用使用完整名称，避免生成字段、方法或用户成员遮蔽类型名。
fn type_ref(namespace: &str, name: &str) -> String {
    let name = csharp_identifier(name);
    if namespace.is_empty() {
        format!("global::{name}")
    } else {
        format!("global::{}.{name}", csharp_identifier(namespace))
    }
}

fn header(namespace: &str) -> String {
    let mut source = String::from("// <auto-generated />\n#nullable enable\n\n");
    if !namespace.is_empty() {
        {
            let _ = write!(source, "namespace {}\n{{\n", csharp_identifier(namespace));
        };
    }
    source
}
fn finish(mut source: String, namespace: &str) -> String {
    if !namespace.is_empty() {
        source.push_str("}\n");
    }
    source
}

// 生成器只输出静态描述和类型明确的构造回调，不复制加载算法。
pub(super) fn generate(
    schema: &CftSchema,
    namespace: &str,
    values: &IdAsEnumValues,
) -> Result<Vec<GeneratedFile>> {
    for segment in namespace.split('.').filter(|_| !namespace.is_empty()) {
        validate_ident(segment)?;
    }
    let mut names = BTreeSet::from(["CoflowData"].map(str::to_string));
    for name in schema
        .all_types()
        .map(|ty| ty.name.as_str())
        .chain(schema.all_enums().map(|en| en.name.as_str()))
    {
        validate_ident(name)?;
        if !names.insert(name.to_string()) {
            return Err(CsharpCodegenError::new(format!(
                "duplicate generated type `{name}`"
            )));
        }
    }
    for ty in schema
        .all_types()
        .filter(|ty| ty.is_table() && schema.inherited_id_as_enum(ty.name.as_str()).is_some())
    {
        let extension = format!("CoflowIds_{}", metadata_identifier(ty.name.as_str()));
        if !names.insert(extension.clone()) {
            return Err(CsharpCodegenError::new(format!(
                "duplicate generated type `{extension}`"
            )));
        }
    }
    let mut files = Vec::new();
    for en in schema.all_enums() {
        files.push(GeneratedFile {
            relative_path: PathBuf::from(format!("{}.cs", en.name)),
            contents: enum_source(en, schema, namespace, values)?,
        });
    }
    for ty in schema.all_types() {
        if !ty.is_data() && ty.name.as_str() == "id" {
            return Err(CsharpCodegenError::new(
                "record type `id` conflicts with its generated identity member",
            ));
        }
        for field in ty.all_fields() {
            validate_ident(field.name.as_str())?;
            if field.name.as_str() == ty.name.as_str()
                || (!ty.is_data() && field.name.as_str() == "id")
            {
                return Err(CsharpCodegenError::new(format!(
                    "field `{}.{}` conflicts with a generated member",
                    ty.name, field.name
                )));
            }
        }
        files.push(GeneratedFile {
            relative_path: PathBuf::from(format!("{}.cs", ty.name)),
            contents: type_source(ty, namespace)?,
        });
    }
    files.push(GeneratedFile {
        relative_path: PathBuf::from("CoflowData.cs"),
        contents: loader_source(schema, namespace, values)?,
    });
    Ok(files)
}

fn enum_variants(
    en: &CftEnum,
    schema: &CftSchema,
    values: &IdAsEnumValues,
) -> Result<Vec<(String, i64)>> {
    if schema.type_for_id_as_enum(&en.name).is_some() {
        let entries = values.get(en.name.as_str()).ok_or_else(|| {
            CsharpCodegenError::new(format!(
                "missing stable values for @idAsEnum enum `{}`",
                en.name
            ))
        })?;
        let mut variants = Vec::new();
        let mut used = BTreeSet::new();
        for (name, value) in entries {
            validate_ident(name)?;
            // 直接调用生成器也遵守编号契约，不能输出负编号或组合 flag 编号。
            if *value < 0 || (en.is_flag && (*value == 0 || (*value & (*value - 1)) != 0)) {
                return Err(CsharpCodegenError::new(format!(
                    "@idAsEnum enum `{}` has invalid stable value `{value}` for `{name}`",
                    en.name
                )));
            }
            if !used.insert(*value) {
                return Err(CsharpCodegenError::new(format!(
                    "@idAsEnum enum `{}` has duplicate stable value `{value}`",
                    en.name
                )));
            }
            if en.is_flag && matches!(name.as_str(), "None" | "Everything") {
                return Err(CsharpCodegenError::new(
                    "record ID conflicts with built-in flag member",
                ));
            }
            variants.push((name.clone(), *value));
        }
        if en.is_flag {
            let everything = entries.values().fold(0, |mask, value| mask | value);
            variants.extend([
                ("None".to_string(), 0),
                ("Everything".to_string(), everything),
            ]);
        }
        Ok(variants)
    } else {
        Ok(en
            .variants
            .iter()
            .map(|variant| (variant.name.to_string(), variant.value))
            .collect())
    }
}

fn enum_source(
    en: &CftEnum,
    schema: &CftSchema,
    namespace: &str,
    values: &IdAsEnumValues,
) -> Result<String> {
    let mut source = header(namespace);
    if en.is_flag {
        source.push_str("[global::System.Flags]\n");
    }
    let underlying = if en.is_int64 { "long" } else { "int" };
    let suffix = if en.is_int64 { "L" } else { "" };
    {
        let _ = write!(
            source,
            "public enum {} : {underlying}\n{{\n",
            csharp_identifier(en.name.as_str())
        );
    };
    for (name, value) in enum_variants(en, schema, values)? {
        validate_ident(&name)?;
        if name == en.name.as_str() || name == "value__" {
            return Err(CsharpCodegenError::new(format!(
                "enum member `{name}` conflicts with generated enum `{}`",
                en.name
            )));
        }
        if !en.is_int64 && i32::try_from(value).is_err() {
            return Err(CsharpCodegenError::new(format!(
                "enum `{}` exceeds int range; add @int64",
                en.name
            )));
        }
        {
            let _ = writeln!(
                source,
                "    {} = {value}{suffix},",
                csharp_identifier(&name)
            );
        };
    }
    source.push_str("}\n");
    Ok(finish(source, namespace))
}

// 业务类型直接存储完整数据，构建期读取器不进入最终对象图。
fn type_source(ty: &CftType, namespace: &str) -> Result<String> {
    let is_struct = ty.is_struct;
    let type_name = csharp_identifier(ty.name.as_str());
    let mut source = header(namespace);
    let modifier = if ty.is_abstract {
        "abstract "
    } else if ty.is_sealed {
        "sealed "
    } else {
        ""
    };
    let kind = if is_struct { "struct" } else { "class" };
    {
        let _ = write!(
            source,
            "public {}partial {kind} {}",
            if is_struct { "" } else { modifier },
            type_name
        );
    };
    if !is_struct {
        if let Some(parent) = &ty.parent {
            {
                let _ = write!(source, " : {}", type_ref(namespace, parent.as_str()));
            };
        }
    }
    source.push_str("\n{\n");
    if !is_struct {
        if ty.is_data() {
            {
                let _ = writeln!(source, "    internal {type_name}() {{ }}");
            };
        } else {
            if ty.parent.is_none() {
                source.push_str("    public string id { get; }\n");
            }
            {
                let _ = write!(source, "    internal {type_name}(string id)");
            };
            if ty.parent.is_some() {
                source.push_str(" : base(id)");
            }
            source.push_str(if ty.parent.is_none() {
                " { this.id = id; }\n"
            } else {
                " { }\n"
            });
        }
    }
    let fields = if is_struct {
        ty.all_fields().collect::<Vec<_>>()
    } else {
        ty.own_fields().collect::<Vec<_>>()
    };
    for field in fields {
        let value_type = field_type(field, namespace)?;
        {
            let _ = writeln!(
                source,
                "    public {value_type} {} {{ get; internal set; }}{}",
                csharp_identifier(field.name.as_str()),
                if is_struct { "" } else { " = default!;" }
            );
        };
    }
    source.push_str("}\n");
    Ok(finish(source, namespace))
}

fn value_type(ty: &CftValueType, namespace: &str) -> Result<String> {
    Ok(match ty {
        CftValueType::Int => "int".into(),
        CftValueType::Long => "long".into(),
        CftValueType::Float => "float".into(),
        CftValueType::Double => "double".into(),
        CftValueType::Bool => "bool".into(),
        CftValueType::String => "string".into(),
        CftValueType::Object(name) | CftValueType::RecordRef(name) => {
            type_ref(namespace, name.as_str())
        }
        CftValueType::Enum(name) => type_ref(namespace, name.as_str()),
        CftValueType::Array(inner) => format!(
            "global::System.Collections.Generic.IReadOnlyList<{}>",
            value_type(inner, namespace)?
        ),
        CftValueType::Dict(key, value) => format!(
            "global::System.Collections.Generic.IReadOnlyDictionary<{}, {}>",
            value_type(key, namespace)?,
            value_type(value, namespace)?
        ),
        CftValueType::Option(inner) => {
            format!(
                "global::Coflow.Loader.Option<{}>",
                value_type(inner, namespace)?
            )
        }
    })
}
fn field_type(field: &CftField, namespace: &str) -> Result<String> {
    value_type(&field.value_type, namespace)
}
fn value_descriptor(ty: &CftValueType, namespace: &str) -> Result<String> {
    Ok(match ty {
        CftValueType::Int => "global::Coflow.Loader.CfdValues.Int".into(),
        CftValueType::Long => "global::Coflow.Loader.CfdValues.Long".into(),
        CftValueType::Double => "global::Coflow.Loader.CfdValues.Double".into(),
        CftValueType::Float => "global::Coflow.Loader.CfdValues.Float".into(),
        CftValueType::Bool => "global::Coflow.Loader.CfdValues.Bool".into(),
        CftValueType::String => "global::Coflow.Loader.CfdValues.String".into(),
        CftValueType::Object(name) => format!(
            "global::Coflow.Loader.CfdValues.Object<{}>({})",
            type_ref(namespace, name.as_str()),
            quote(name.as_str())
        ),
        CftValueType::RecordRef(name) => format!(
            "global::Coflow.Loader.CfdValues.Reference<{}>({})",
            type_ref(namespace, name.as_str()),
            quote(name.as_str())
        ),
        CftValueType::Enum(name) => format!("Enum_{}", metadata_identifier(name.as_str())),
        CftValueType::Array(inner) => format!(
            "global::Coflow.Loader.CfdValues.List({})",
            value_descriptor(inner, namespace)?
        ),
        CftValueType::Dict(key, value) => format!(
            "global::Coflow.Loader.CfdValues.Dictionary({}, {})",
            value_descriptor(key, namespace)?,
            value_descriptor(value, namespace)?
        ),
        CftValueType::Option(inner) => format!(
            "global::Coflow.Loader.CfdValues.Optional({})",
            value_descriptor(inner, namespace)?
        ),
    })
}

fn loader_source(schema: &CftSchema, namespace: &str, values: &IdAsEnumValues) -> Result<String> {
    let mut source = header(namespace);
    source.push_str("public sealed partial class CoflowData\n{\n");
    source.push_str("    private readonly global::Coflow.Loader.CfdData _data;\n    private CoflowData(global::Coflow.Loader.CfdData data) { _data = data; }\n\n");
    source.push_str("    public global::Coflow.Loader.Table<global::Coflow.Loader.Dimension<T>> Table<T>() where T : class => _data.Table<T>();\n    public global::Coflow.Loader.Dimension<T> Singleton<T>() where T : class => _data.Singleton<T>();\n    public global::Coflow.Loader.CfdSnapshot Base => _data.Base;\n    public global::Coflow.Loader.CfdSnapshot For(string dimension, string variant) => _data.For(dimension, variant);\n    public global::Coflow.Loader.CfdSnapshot For(params (string Dimension, string Variant)[] selection) => _data.For(selection);\n    public global::Coflow.Loader.CfdSnapshot For(global::Coflow.Loader.DimensionSelection selection) => _data.For(selection);\n\n");
    source.push_str("    public static global::Coflow.Loader.LoadResult<CoflowData> Load(global::System.Collections.Generic.IEnumerable<global::Coflow.Loader.CfdSource> sources, global::Coflow.Loader.LoadOptions? options = null)\n        => global::Coflow.Loader.CfdLoader.Load(sources, Types, data => new CoflowData(data), Constants, options);\n\n");
    for en in schema.all_enums() {
        {
            let _ = write!(source, "    private static readonly global::Coflow.Loader.CfdValueType<{}> Enum_{} = global::Coflow.Loader.CfdValues.Enum<{}>({}, new global::System.Collections.Generic.Dictionary<string, {}>\n    {{\n", type_ref(namespace, en.name.as_str()), metadata_identifier(en.name.as_str()), type_ref(namespace, en.name.as_str()), quote(en.name.as_str()), type_ref(namespace, en.name.as_str()));
        };
        for (name, _) in enum_variants(en, schema, values)? {
            {
                let _ = writeln!(
                    source,
                    "        [{}] = {}.{},",
                    quote(&name),
                    type_ref(namespace, en.name.as_str()),
                    csharp_identifier(&name)
                );
            };
        }
        {
            let _ = writeln!(
                source,
                "    }}{});",
                if en.is_flag {
                    format!(", bits => ({})bits", type_ref(namespace, en.name.as_str()))
                } else {
                    String::new()
                }
            );
        };
    }
    source.push_str("    private static readonly global::Coflow.Loader.CfdType[] Types = new global::Coflow.Loader.CfdType[]\n    {\n");
    for ty in schema.all_types() {
        source.push_str(&type_descriptor(ty, schema, namespace)?);
    }
    source.push_str("    };\n\n    private static readonly global::System.Collections.Generic.IReadOnlyDictionary<string, global::Coflow.Loader.CfdValueNode> Constants = new global::System.Collections.Generic.Dictionary<string, global::Coflow.Loader.CfdValueNode>\n    {\n");
    for constant in schema.all_consts() {
        {
            let _ = writeln!(
                source,
                "        [{}] = {},",
                quote(constant.name.as_str()),
                const_node(&constant.value)?
            );
        };
    }
    source.push_str("    };\n");
    source.push_str(&table_id_maps(schema, namespace, values)?);
    source.push_str("}\n");
    source.push_str(&table_id_extensions(schema, namespace));
    Ok(finish(source, namespace))
}

// 同一枚举的编号映射只生成一次；独立静态容器在枚举查询时初始化，避免拖慢普通加载。
fn table_id_maps(schema: &CftSchema, namespace: &str, values: &IdAsEnumValues) -> Result<String> {
    let mut source = String::new();
    for en in schema
        .all_enums()
        .filter(|en| schema.type_for_id_as_enum(&en.name).is_some())
    {
        let enum_name = type_ref(namespace, en.name.as_str());
        let field_name = format!("Ids_{}", metadata_identifier(en.name.as_str()));
        let _ = write!(source, "\n    internal static class {field_name}\n    {{\n        internal static readonly global::Coflow.Loader.TableIdMap<{enum_name}> Value = new global::Coflow.Loader.TableIdMap<{enum_name}>(new global::System.Collections.Generic.Dictionary<{enum_name}, string>\n        {{\n");
        let entries = values
            .get(en.name.as_str())
            .ok_or_else(|| CsharpCodegenError::new(format!("missing id mapping `{}`", en.name)))?;
        for key in entries.keys() {
            validate_ident(key)?;
            let _ = writeln!(
                source,
                "            [{enum_name}.{}] = {},",
                csharp_identifier(key),
                quote(key)
            );
        }
        source.push_str("        });\n    }\n");
    }
    Ok(source)
}

// 每张表保留接收者明确的扩展，编译期拒绝其他表的 id enum。
fn table_id_extensions(schema: &CftSchema, namespace: &str) -> String {
    let mut source = String::new();
    for ty in schema.all_types().filter(|ty| ty.is_table()) {
        let Some(enum_name) = schema.inherited_id_as_enum(ty.name.as_str()) else {
            continue;
        };
        let map = format!(
            "{}.Ids_{}.Value",
            type_ref(namespace, "CoflowData"),
            metadata_identifier(enum_name.as_str())
        );
        let enum_name = type_ref(namespace, enum_name.as_str());
        let type_name = type_ref(namespace, ty.name.as_str());
        let extension_name = format!("CoflowIds_{}", metadata_identifier(ty.name.as_str()));
        let _ = write!(source, "\npublic static partial class {extension_name}\n{{\n    public static {type_name} Get(this global::Coflow.Loader.Table<{type_name}> table, {enum_name} id) => table[{map}.GetId(id)];\n    public static bool TryGet(this global::Coflow.Loader.Table<{type_name}> table, {enum_name} id, out {type_name} value)\n    {{\n        if ({map}.TryGetId(id, out var text)) return table.TryGetValue(text, out value);\n        value = null!;\n        return false;\n    }}\n    public static global::Coflow.Loader.Dimension<{type_name}> Get(this global::Coflow.Loader.Table<global::Coflow.Loader.Dimension<{type_name}>> table, {enum_name} id) => table[{map}.GetId(id)];\n    public static bool TryGet(this global::Coflow.Loader.Table<global::Coflow.Loader.Dimension<{type_name}>> table, {enum_name} id, out global::Coflow.Loader.Dimension<{type_name}> value)\n    {{\n        if ({map}.TryGetId(id, out var text)) return table.TryGetValue(text, out value);\n        value = null!;\n        return false;\n    }}\n}}\n");
    }
    source
}

fn type_descriptor(ty: &CftType, schema: &CftSchema, namespace: &str) -> Result<String> {
    let mut source = format!("        new global::Coflow.Loader.CfdType<{}>({}, global::Coflow.Loader.CfdTypeKind.{}, new global::Coflow.Loader.CfdField[]\n        {{\n", type_ref(namespace, ty.name.as_str()), quote(ty.name.as_str()), if ty.is_data() { "Data" } else if ty.is_singleton() { "Singleton" } else { "Table" });
    for field in ty.all_fields() {
        let descriptor = value_descriptor(&field.value_type, namespace)?;
        {
            let _ = writeln!(
                source,
                "            new global::Coflow.Loader.CfdField<{}>({}, {}{}{}),",
                field_type(field, namespace)?,
                quote(field.name.as_str()),
                descriptor,
                match &field.default {
                    Some(value) => format!(", {}", default_node(value, &field.value_type, schema)?),
                    None => String::new(),
                },
                field
                    .dimension
                    .as_ref()
                    .map(|dimension| format!(
                        ", dimension: {}",
                        quote(dimension.dimension.as_str())
                    ))
                    .unwrap_or_default()
            );
        };
    }
    source.push_str("        }, ");
    if ty.is_abstract {
        source.push_str("create: null, fill: null, abstractType: true");
    } else {
        let _ = write!(
            source,
            "create: id => new {}({}), fill: (value, reader) =>\n        {{\n",
            type_ref(namespace, ty.name.as_str()),
            if ty.is_data() { "" } else { "id" }
        );
        // 同一字段序号用于描述和一次性赋值；结构体通过返回值完成赋值。
        for (ordinal, field) in ty.all_fields().enumerate() {
            let _ = writeln!(
                source,
                "            value.{} = reader.Get<{}>({ordinal});",
                csharp_identifier(field.name.as_str()),
                field_type(field, namespace)?
            );
        }
        source.push_str("            return value;\n        }");
    }
    if let Some(parent) = &ty.parent {
        {
            let _ = write!(source, ", parent: {}", quote(parent.as_str()));
        };
    }
    source.push_str("),\n");
    Ok(source)
}

#[expect(
    clippy::too_many_lines,
    reason = "按语言或命令分支集中处理，保持分派与各分支语义可直接核对。"
)]
fn default_node(
    value: &CftSchemaDefaultValue,
    expected: &CftValueType,
    schema: &CftSchema,
) -> Result<String> {
    use CftSchemaDefaultValue as V;
    Ok(match value {
        V::Int(value) => integer_node(*value),
        V::Float(value) => float_node(*value)?,
        V::Bool(value) => format!("global::Coflow.Loader.CfdDefaults.Bool({value})"),
        V::String(value) => format!("global::Coflow.Loader.CfdDefaults.String({})", quote(value)),
        V::FormattedString(source) => format!(
            "global::Coflow.Loader.CfdDefaults.Template({})",
            quote(&source.source)
        ),
        V::OptionNone => "global::Coflow.Loader.CfdDefaults.None()".into(),
        V::OptionSome(value) => format!(
            "global::Coflow.Loader.CfdDefaults.Some({})",
            default_node(
                value,
                if let CftValueType::Option(inner) = expected {
                    inner
                } else {
                    expected
                },
                schema,
            )?
        ),
        V::Enum {
            enum_name, value, ..
        } => format!(
            "global::Coflow.Loader.CfdDefaults.Enum({}, {value}L)",
            quote(enum_name.as_str())
        ),
        V::RecordReference { type_name, id } => format!(
            "global::Coflow.Loader.CfdDefaults.Reference({}, {})",
            quote(type_name.as_str()),
            quote(id)
        ),
        V::EmptyArray => "global::Coflow.Loader.CfdDefaults.Array()".into(),
        V::EmptyObject => {
            if let CftValueType::Object(name) = expected {
                format!(
                    "global::Coflow.Loader.CfdDefaults.Object({})",
                    quote(name.as_str())
                )
            } else {
                "global::Coflow.Loader.CfdDefaults.Dictionary()".into()
            }
        }
        V::Array(items) => format!(
            "global::Coflow.Loader.CfdDefaults.Array({})",
            items
                .iter()
                .map(|item| default_node(
                    item,
                    if let CftValueType::Array(inner) = expected {
                        inner
                    } else {
                        expected
                    },
                    schema
                ))
                .collect::<Result<Vec<_>>>()?
                .join(", ")
        ),
        V::Dictionary(entries) => {
            let (key_ty, value_ty) = if let CftValueType::Dict(key, value) = expected {
                (&**key, &**value)
            } else {
                (expected, expected)
            };
            format!(
                "global::Coflow.Loader.CfdDefaults.Dictionary({})",
                entries
                    .iter()
                    .map(|(key, value)| Ok(format!(
                        "new global::Coflow.Loader.CfdDefaultEntry({}, {})",
                        default_node(key, key_ty, schema)?,
                        default_node(value, value_ty, schema)?
                    )))
                    .collect::<Result<Vec<_>>>()?
                    .join(", ")
            )
        }
        V::Object { type_name, fields } => format!(
            "global::Coflow.Loader.CfdDefaults.Object({}{})",
            quote(type_name.as_str()),
            fields
                .iter()
                .map(|(name, value)| {
                    let field = schema
                        .resolve_type(type_name.as_str())
                        .and_then(|ty| ty.field(name.as_str()))
                        .ok_or_else(|| {
                            CsharpCodegenError::new(format!(
                                "unknown default field `{type_name}.{name}`"
                            ))
                        })?;
                    Ok(format!(
                        ", new global::Coflow.Loader.CfdDefaultField({}, {})",
                        quote(name.as_str()),
                        default_node(value, &field.value_type, schema)?
                    ))
                })
                .collect::<Result<Vec<_>>>()?
                .join("")
        ),
    })
}
fn integer_node(value: i64) -> String {
    format!("global::Coflow.Loader.CfdDefaults.Int({value}L)")
}
fn float_node(value: f64) -> Result<String> {
    if !value.is_finite() {
        return Err(CsharpCodegenError::new("float default must be finite"));
    }
    Ok(format!(
        "global::Coflow.Loader.CfdDefaults.Float({value:?}d)"
    ))
}
fn const_node(value: &CftConstValue) -> Result<String> {
    use CftConstValue as V;
    Ok(match value {
        V::Int(value) => integer_node(*value),
        V::Long(value) => format!("global::Coflow.Loader.CfdDefaults.Long({value}L)"),
        V::Float(value) => float_node(*value)?,
        V::Double(value) => format!("global::Coflow.Loader.CfdDefaults.Double({value:?}d)"),
        V::Bool(value) => format!("global::Coflow.Loader.CfdDefaults.Bool({value})"),
        V::String(value) => format!("global::Coflow.Loader.CfdDefaults.String({})", quote(value)),
        V::FormattedString(source) => format!(
            "global::Coflow.Loader.CfdDefaults.Template({})",
            quote(&source.source)
        ),
        V::OptionNone => "global::Coflow.Loader.CfdDefaults.None()".into(),
        V::OptionSome(value) => format!(
            "global::Coflow.Loader.CfdDefaults.Some({})",
            const_node(value)?
        ),
        V::Enum {
            enum_name, value, ..
        } => format!(
            "global::Coflow.Loader.CfdDefaults.Enum({}, {value}L)",
            quote(enum_name.as_str())
        ),
        V::RecordReference { type_name, id } => format!(
            "global::Coflow.Loader.CfdDefaults.Reference({}, {})",
            quote(type_name.as_str()),
            quote(id)
        ),
        V::Array(items) => format!(
            "global::Coflow.Loader.CfdDefaults.Array({})",
            items
                .iter()
                .map(const_node)
                .collect::<Result<Vec<_>>>()?
                .join(", ")
        ),
        V::Dictionary(entries) => format!(
            "global::Coflow.Loader.CfdDefaults.Dictionary({})",
            entries
                .iter()
                .map(|(key, value)| Ok(format!(
                    "new global::Coflow.Loader.CfdDefaultEntry({}, {})",
                    const_node(key)?,
                    const_node(value)?
                )))
                .collect::<Result<Vec<_>>>()?
                .join(", ")
        ),
        V::Object { type_name, fields } => format!(
            "global::Coflow.Loader.CfdDefaults.Object({}{})",
            quote(type_name.as_str()),
            fields
                .iter()
                .map(|(name, value)| Ok(format!(
                    ", new global::Coflow.Loader.CfdDefaultField({}, {})",
                    quote(name.as_str()),
                    const_node(value)?
                )))
                .collect::<Result<Vec<_>>>()?
                .join("")
        ),
    })
}
