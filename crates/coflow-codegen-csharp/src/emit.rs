use crate::{
    names::{csharp_ident_error, metadata_identifier},
    CsharpCodegenError, GeneratedFile,
};
use coflow_codegen::IdAsEnumValues;
use coflow_language::cft::{
    CftConstValue, CftEnum, CftField, CftSchema, CftSchemaDefaultValue, CftType, CftValueType,
};
use std::{collections::BTreeSet, path::PathBuf};

type Result<T> = std::result::Result<T, CsharpCodegenError>;

fn quote(text: &str) -> String {
    let mut out = String::from("\"");
    for ch in text.chars() {
        match ch {
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            ch if ch.is_control() => out.push_str(&format!("\\u{:04X}", u32::from(ch))),
            ch => out.push(ch),
        }
    }
    out.push('"');
    out
}

fn validate_ident(name: &str) -> Result<()> {
    if let Some(error) = csharp_ident_error(name) {
        return Err(CsharpCodegenError::new(format!(
            "invalid C# identifier `{name}`: {error}"
        )));
    }
    Ok(())
}

fn header(namespace: &str) -> String {
    let mut source = String::from("// <auto-generated />\n#nullable enable\n\n");
    if !namespace.is_empty() {
        source.push_str(&format!("namespace {namespace}\n{{\n"));
    }
    source
}
fn finish(mut source: String, namespace: &str) -> String {
    if !namespace.is_empty() {
        source.push_str("}\n");
    }
    source
}

// 生成器只输出静态描述和类型明确的构造回调，不复制加载算法。
pub(super) fn generate(
    schema: &CftSchema,
    namespace: &str,
    values: &IdAsEnumValues,
) -> Result<Vec<GeneratedFile>> {
    for segment in namespace.split('.').filter(|_| !namespace.is_empty()) {
        validate_ident(segment)?;
    }
    let mut names =
        BTreeSet::from(["CoflowData", "Load", "Types", "Constants"].map(str::to_string));
    for name in schema
        .all_types()
        .map(|ty| ty.name.as_str())
        .chain(schema.all_enums().map(|en| en.name.as_str()))
    {
        validate_ident(name)?;
        if !names.insert(name.to_string()) {
            return Err(CsharpCodegenError::new(format!(
                "duplicate generated type `{name}`"
            )));
        }
    }
    for ty in schema.all_types().filter(|ty| ty.is_struct) {
        let record_name = record_type_name(ty);
        if !names.insert(record_name.clone()) {
            return Err(CsharpCodegenError::new(format!(
                "duplicate generated type `{record_name}`"
            )));
        }
    }
    let mut files = Vec::new();
    for en in schema.all_enums() {
        files.push(GeneratedFile {
            relative_path: PathBuf::from(format!("{}.cs", en.name)),
            contents: enum_source(en, schema, namespace, values)?,
        });
    }
    for ty in schema.all_types() {
        for field in ty.all_fields() {
            validate_ident(field.name.as_str())?;
            if field.name.as_str() == ty.name.as_str()
                || field.name.as_str() == record_type_name(ty)
                || field.name.as_str() == "id"
            {
                return Err(CsharpCodegenError::new(format!(
                    "field `{}.{}` conflicts with a generated member",
                    ty.name, field.name
                )));
            }
        }
        files.push(GeneratedFile {
            relative_path: PathBuf::from(format!("{}.cs", ty.name)),
            contents: type_source(ty, schema, namespace, false)?,
        });
        if ty.is_struct {
            files.push(GeneratedFile {
                relative_path: PathBuf::from(format!("{}.cs", record_type_name(ty))),
                contents: type_source(ty, schema, namespace, true)?,
            });
        }
    }
    files.push(GeneratedFile {
        relative_path: PathBuf::from("CoflowData.cs"),
        contents: loader_source(schema, namespace, values)?,
    });
    Ok(files)
}

fn enum_variants(
    en: &CftEnum,
    schema: &CftSchema,
    values: &IdAsEnumValues,
) -> Result<Vec<(String, i64)>> {
    if schema.type_for_id_as_enum(&en.name).is_some() {
        let entries = values.get(en.name.as_str()).ok_or_else(|| {
            CsharpCodegenError::new(format!(
                "missing stable values for @idAsEnum enum `{}`",
                en.name
            ))
        })?;
        entries
            .iter()
            .map(|(name, value)| {
                validate_ident(name)?;
                Ok((name.clone(), *value))
            })
            .collect()
    } else {
        Ok(en
            .variants
            .iter()
            .map(|variant| (variant.name.to_string(), variant.value))
            .collect())
    }
}

fn enum_source(
    en: &CftEnum,
    schema: &CftSchema,
    namespace: &str,
    values: &IdAsEnumValues,
) -> Result<String> {
    let mut source = header(namespace);
    if en.is_flag {
        source.push_str("[global::System.Flags]\n");
    }
    source.push_str(&format!("public enum {} : long\n{{\n", en.name));
    for (name, value) in enum_variants(en, schema, values)? {
        validate_ident(&name)?;
        source.push_str(&format!("    {name} = {value}L,\n"));
    }
    source.push_str("}\n");
    Ok(finish(source, namespace))
}

// 内联结构体与记录身份分别生成，引用始终连接可先分配的记录类。
fn record_type_name(ty: &CftType) -> String {
    if ty.is_struct {
        format!("{}Record", ty.name)
    } else {
        ty.name.to_string()
    }
}

fn reference_type_name(name: &str, schema: &CftSchema) -> Result<String> {
    schema
        .resolve_type(name)
        .map(record_type_name)
        .ok_or_else(|| CsharpCodegenError::new(format!("unknown reference type `{name}`")))
}

fn type_source(ty: &CftType, schema: &CftSchema, namespace: &str, record: bool) -> Result<String> {
    let is_struct = ty.is_struct && !record;
    let type_name = if record {
        record_type_name(ty)
    } else {
        ty.name.to_string()
    };
    let mut source = header(namespace);
    let modifier = if ty.is_abstract {
        "abstract "
    } else if ty.is_sealed {
        "sealed "
    } else {
        ""
    };
    let kind = if is_struct { "struct" } else { "class" };
    source.push_str(&format!(
        "public {}{kind} {}",
        if is_struct { "" } else { modifier },
        type_name
    ));
    if !is_struct {
        if let Some(parent) = &ty.parent {
            source.push_str(&format!(
                " : {}",
                reference_type_name(parent.as_str(), schema)?
            ));
        }
    }
    source.push_str("\n{\n");
    if !is_struct {
        if ty.parent.is_none() {
            source.push_str("    public string? id { get; }\n");
        }
        source.push_str(&format!("    internal {type_name}(string? key)"));
        if ty.parent.is_some() {
            source.push_str(" : base(key)");
        }
        source.push_str(if ty.parent.is_none() {
            " { id = key; }\n"
        } else {
            " { }\n"
        });
    }
    let fields = if is_struct {
        ty.all_fields().collect::<Vec<_>>()
    } else {
        ty.own_fields().collect::<Vec<_>>()
    };
    for field in fields {
        let value_type = field_type(field, schema)?;
        source.push_str(&format!(
            "    public {value_type} {} {{ get; internal set; }}{}\n",
            field.name,
            if is_struct { "" } else { " = default!;" }
        ));
    }
    source.push_str("}\n");
    Ok(finish(source, namespace))
}

fn value_type(ty: &CftValueType, schema: &CftSchema) -> Result<String> {
    Ok(match ty {
        CftValueType::Int => "long".into(),
        CftValueType::Float => "double".into(),
        CftValueType::Bool => "bool".into(),
        CftValueType::String | CftValueType::FormattedString => "string".into(),
        CftValueType::Object(name) => name.to_string(),
        CftValueType::RecordRef(name) => reference_type_name(name.as_str(), schema)?,
        CftValueType::Enum(name) => name.to_string(),
        CftValueType::Array(inner) => format!(
            "global::System.Collections.Generic.IReadOnlyList<{}>",
            value_type(inner, schema)?
        ),
        CftValueType::Dict(key, value) => format!(
            "global::System.Collections.Generic.IReadOnlyDictionary<{}, {}>",
            value_type(key, schema)?,
            value_type(value, schema)?
        ),
        CftValueType::Option(inner) => format!(
            "global::Coflow.Loader.Option<{}>",
            value_type(inner, schema)?
        ),
    })
}
fn field_type(field: &CftField, schema: &CftSchema) -> Result<String> {
    let ty = value_type(&field.value_type, schema)?;
    Ok(if field.dimension.is_some() {
        format!("global::Coflow.Loader.DimensionValue<{ty}>")
    } else {
        ty
    })
}
fn value_descriptor(ty: &CftValueType, schema: &CftSchema) -> Result<String> {
    Ok(match ty {
        CftValueType::Int => "global::Coflow.Loader.CfdValues.Int".into(),
        CftValueType::Float => "global::Coflow.Loader.CfdValues.Float".into(),
        CftValueType::Bool => "global::Coflow.Loader.CfdValues.Bool".into(),
        CftValueType::String => "global::Coflow.Loader.CfdValues.String".into(),
        CftValueType::FormattedString => "global::Coflow.Loader.CfdValues.FormattedString".into(),
        CftValueType::Object(name) => format!(
            "global::Coflow.Loader.CfdValues.Object<{}>({})",
            name,
            quote(name.as_str())
        ),
        CftValueType::RecordRef(name) => format!(
            "global::Coflow.Loader.CfdValues.Reference<{}>({})",
            reference_type_name(name.as_str(), schema)?,
            quote(name.as_str())
        ),
        CftValueType::Enum(name) => format!("Enum_{}", metadata_identifier(name.as_str())),
        CftValueType::Array(inner) => format!(
            "global::Coflow.Loader.CfdValues.List({})",
            value_descriptor(inner, schema)?
        ),
        CftValueType::Dict(key, value) => format!(
            "global::Coflow.Loader.CfdValues.Dictionary({}, {})",
            value_descriptor(key, schema)?,
            value_descriptor(value, schema)?
        ),
        CftValueType::Option(inner) => format!(
            "global::Coflow.Loader.CfdValues.Optional({})",
            value_descriptor(inner, schema)?
        ),
    })
}

fn loader_source(schema: &CftSchema, namespace: &str, values: &IdAsEnumValues) -> Result<String> {
    let mut source = header(namespace);
    source.push_str("public sealed class CoflowData\n{\n");
    let records = schema.all_types().collect::<Vec<_>>();
    for ty in &records {
        let ty_name = &ty.name;
        let record_name = record_type_name(ty);
        if ty.is_singleton {
            source.push_str(&format!("    public {record_name} {ty_name} {{ get; }}\n"));
        } else {
            source.push_str(&format!("    public global::System.Collections.Generic.IReadOnlyDictionary<string, {record_name}> {ty_name} {{ get; }}\n"));
        }
    }
    source.push_str("    private CoflowData(global::Coflow.Loader.CfdData data)\n    {\n");
    for ty in &records {
        source.push_str(&format!(
            "        {} = data.{}<{}>();\n",
            ty.name,
            if ty.is_singleton {
                "Singleton"
            } else {
                "Records"
            },
            record_type_name(ty)
        ));
    }
    source.push_str("    }\n\n    public static global::Coflow.Loader.LoadResult<CoflowData> Load(global::System.Collections.Generic.IEnumerable<global::Coflow.Loader.CfdSource> sources)\n        => global::Coflow.Loader.CfdLoader.Load(sources, Types, data => new CoflowData(data), Constants);\n\n");
    for en in schema.all_enums() {
        source.push_str(&format!("    private static readonly global::Coflow.Loader.CfdValueType<{}> Enum_{} = global::Coflow.Loader.CfdValues.Enum<{}>({}, new global::System.Collections.Generic.Dictionary<string, {}>\n    {{\n", en.name, metadata_identifier(en.name.as_str()), en.name, quote(en.name.as_str()), en.name));
        for (name, _) in enum_variants(en, schema, values)? {
            source.push_str(&format!(
                "        [{}] = {}.{name},\n",
                quote(&name),
                en.name
            ));
        }
        source.push_str(&format!(
            "    }}{});\n",
            if en.is_flag {
                format!(", bits => ({})bits", en.name)
            } else {
                String::new()
            }
        ));
    }
    source.push_str("    private static readonly global::Coflow.Loader.CfdType[] Types = new global::Coflow.Loader.CfdType[]\n    {\n");
    for ty in schema.all_types() {
        source.push_str(&type_descriptor(ty, schema)?);
    }
    source.push_str("    };\n\n    private static readonly global::System.Collections.Generic.IReadOnlyDictionary<string, global::Coflow.Loader.CfdValueNode> Constants = new global::System.Collections.Generic.Dictionary<string, global::Coflow.Loader.CfdValueNode>\n    {\n");
    for constant in schema.all_consts() {
        source.push_str(&format!(
            "        [{}] = {},\n",
            quote(constant.name.as_str()),
            const_node(&constant.value)?
        ));
    }
    source.push_str("    };\n}\n");
    Ok(finish(source, namespace))
}

fn type_descriptor(ty: &CftType, schema: &CftSchema) -> Result<String> {
    let record_name = record_type_name(ty);
    let mut source = format!("        new global::Coflow.Loader.CfdType<{}, {}>({}, new global::Coflow.Loader.CfdField[]\n        {{\n", ty.name, record_name, quote(ty.name.as_str()));
    for field in ty.all_fields() {
        let mut descriptor = value_descriptor(&field.value_type, schema)?;
        if let Some(dimension) = &field.dimension {
            descriptor = format!(
                "global::Coflow.Loader.CfdValues.Dimension({}, {descriptor})",
                quote(dimension.dimension.as_str())
            );
        }
        source.push_str(&format!(
            "            new global::Coflow.Loader.CfdField<{}>({}, {}{}),\n",
            field_type(field, schema)?,
            quote(field.name.as_str()),
            descriptor,
            match &field.default {
                Some(value) => format!(", {}", default_node(value, &field.value_type, schema)?),
                None => String::new(),
            }
        ));
    }
    source.push_str("        }, ");
    if ty.is_abstract {
        source.push_str("create: null, fill: null, construct: null, abstractType: true");
    } else {
        source.push_str(&format!(
            "key => new {record_name}(key), (value, reader) =>\n        {{\n"
        ));
        for field in ty.all_fields() {
            source.push_str(&format!(
                "            value.{} = reader.Get<{}>({});\n",
                field.name,
                field_type(field, schema)?,
                quote(field.name.as_str())
            ));
        }
        source.push_str(&format!(
            "        }}, reader => new {}{}\n        {{\n",
            ty.name,
            if ty.is_struct { "" } else { "(null)" }
        ));
        for field in ty.all_fields() {
            source.push_str(&format!(
                "            {} = reader.Get<{}>({}),\n",
                field.name,
                field_type(field, schema)?,
                quote(field.name.as_str())
            ));
        }
        source.push_str("        }");
        if ty.is_singleton {
            source.push_str(", singleton: true");
        }
    }
    if let Some(parent) = &ty.parent {
        source.push_str(&format!(", parent: {}", quote(parent.as_str())));
    }
    if ty.is_struct {
        source.push_str(", structValue: true");
    }
    source.push_str("),\n");
    Ok(source)
}

fn default_node(
    value: &CftSchemaDefaultValue,
    expected: &CftValueType,
    schema: &CftSchema,
) -> Result<String> {
    use CftSchemaDefaultValue as V;
    Ok(match value {
        V::Int(value) => integer_node(*value)?,
        V::Float(value) => float_node(*value)?,
        V::Bool(value) => format!("global::Coflow.Loader.CfdDefaults.Bool({value})"),
        V::String(value) => format!("global::Coflow.Loader.CfdDefaults.String({})", quote(value)),
        V::FormattedString(source) => format!(
            "global::Coflow.Loader.CfdDefaults.Template({})",
            quote(source)
        ),
        V::OptionNone => "global::Coflow.Loader.CfdDefaults.None()".into(),
        V::OptionSome(value) => format!(
            "global::Coflow.Loader.CfdDefaults.Some({})",
            default_node(
                value,
                if let CftValueType::Option(inner) = expected {
                    inner
                } else {
                    expected
                },
                schema,
            )?
        ),
        V::Enum {
            enum_name, value, ..
        } => format!(
            "global::Coflow.Loader.CfdDefaults.Enum({}, {value}L)",
            quote(enum_name.as_str())
        ),
        V::RecordReference { type_name, key } => format!(
            "global::Coflow.Loader.CfdDefaults.Reference({}, {})",
            quote(type_name.as_str()),
            quote(key)
        ),
        V::EmptyArray => "global::Coflow.Loader.CfdDefaults.Array()".into(),
        V::EmptyObject => {
            if let CftValueType::Object(name) = expected {
                format!(
                    "global::Coflow.Loader.CfdDefaults.Object({})",
                    quote(name.as_str())
                )
            } else {
                "global::Coflow.Loader.CfdDefaults.Dictionary()".into()
            }
        }
        V::Array(items) => format!(
            "global::Coflow.Loader.CfdDefaults.Array({})",
            items
                .iter()
                .map(|item| default_node(
                    item,
                    if let CftValueType::Array(inner) = expected {
                        inner
                    } else {
                        expected
                    },
                    schema
                ))
                .collect::<Result<Vec<_>>>()?
                .join(", ")
        ),
        V::Dictionary(entries) => {
            let (key_ty, value_ty) = if let CftValueType::Dict(key, value) = expected {
                (&**key, &**value)
            } else {
                (expected, expected)
            };
            format!(
                "global::Coflow.Loader.CfdDefaults.Dictionary({})",
                entries
                    .iter()
                    .map(|(key, value)| Ok(format!(
                        "new global::Coflow.Loader.CfdDefaultEntry({}, {})",
                        default_node(key, key_ty, schema)?,
                        default_node(value, value_ty, schema)?
                    )))
                    .collect::<Result<Vec<_>>>()?
                    .join(", ")
            )
        }
        V::Object { type_name, fields } => format!(
            "global::Coflow.Loader.CfdDefaults.Object({}{})",
            quote(type_name.as_str()),
            fields
                .iter()
                .map(|(name, value)| {
                    let field = schema
                        .resolve_type(type_name.as_str())
                        .and_then(|ty| ty.field(name.as_str()))
                        .ok_or_else(|| {
                            CsharpCodegenError::new(format!(
                                "unknown default field `{type_name}.{name}`"
                            ))
                        })?;
                    Ok(format!(
                        ", new global::Coflow.Loader.CfdDefaultField({}, {})",
                        quote(name.as_str()),
                        default_node(value, &field.value_type, schema)?
                    ))
                })
                .collect::<Result<Vec<_>>>()?
                .join("")
        ),
    })
}
fn integer_node(value: i64) -> Result<String> {
    Ok(format!("global::Coflow.Loader.CfdDefaults.Int({value}L)"))
}
fn float_node(value: f64) -> Result<String> {
    if !value.is_finite() {
        return Err(CsharpCodegenError::new("float default must be finite"));
    }
    Ok(format!(
        "global::Coflow.Loader.CfdDefaults.Float({value:?}d)"
    ))
}
fn const_node(value: &CftConstValue) -> Result<String> {
    use CftConstValue as V;
    Ok(match value {
        V::Int(value) => integer_node(*value)?,
        V::Float(value) => float_node(*value)?,
        V::Bool(value) => format!("global::Coflow.Loader.CfdDefaults.Bool({value})"),
        V::String(value) => format!("global::Coflow.Loader.CfdDefaults.String({})", quote(value)),
        V::FormattedString(source) => format!(
            "global::Coflow.Loader.CfdDefaults.Template({})",
            quote(source)
        ),
        V::OptionNone => "global::Coflow.Loader.CfdDefaults.None()".into(),
        V::OptionSome(value) => format!(
            "global::Coflow.Loader.CfdDefaults.Some({})",
            const_node(value)?
        ),
        V::Enum {
            enum_name, value, ..
        } => format!(
            "global::Coflow.Loader.CfdDefaults.Enum({}, {value}L)",
            quote(enum_name.as_str())
        ),
        V::RecordReference { type_name, key } => format!(
            "global::Coflow.Loader.CfdDefaults.Reference({}, {})",
            quote(type_name.as_str()),
            quote(key)
        ),
        V::Array(items) => format!(
            "global::Coflow.Loader.CfdDefaults.Array({})",
            items
                .iter()
                .map(const_node)
                .collect::<Result<Vec<_>>>()?
                .join(", ")
        ),
        V::Dictionary(entries) => format!(
            "global::Coflow.Loader.CfdDefaults.Dictionary({})",
            entries
                .iter()
                .map(|(key, value)| Ok(format!(
                    "new global::Coflow.Loader.CfdDefaultEntry({}, {})",
                    const_node(key)?,
                    const_node(value)?
                )))
                .collect::<Result<Vec<_>>>()?
                .join(", ")
        ),
        V::Object { type_name, fields } => format!(
            "global::Coflow.Loader.CfdDefaults.Object({}{})",
            quote(type_name.as_str()),
            fields
                .iter()
                .map(|(name, value)| Ok(format!(
                    ", new global::Coflow.Loader.CfdDefaultField({}, {})",
                    quote(name.as_str()),
                    const_node(value)?
                )))
                .collect::<Result<Vec<_>>>()?
                .join("")
        ),
    })
}
